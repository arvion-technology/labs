// TypeScript interface generation from the environment schema.
//
// The generated type is the same shape the accessor returns, so a typo in a
// variable name becomes a compile error instead of undefined at runtime.

function tsType(rule) {
  switch (rule.type || "string") {
    case "number":
    case "port":
    case "duration":
      return "number";
    case "boolean":
      return "boolean";
    case "enum":
      return (rule.values || []).map((value) => JSON.stringify(String(value))).join(" | ");
    case "json":
      return "unknown";
    default:
      return "string";
  }
}

export function toTypeScript(schema, { interfaceName = "Env" } = {}) {
  const lines = [
    "// Generated by EnvSafe from the environment schema.",
    "// Values are already coerced, so the accessor returns these types directly.",
    `export interface ${interfaceName} {`,
  ];
  for (const [key, rule] of Object.entries(schema)) {
    if (rule.description) lines.push(`  /** ${rule.description} */`);
    const optional = rule.required ? "" : "?";
    lines.push(`  ${key}${optional}: ${tsType(rule)};`);
  }
  lines.push("}", "", `export type ${interfaceName}Key = keyof ${interfaceName};`);
  return lines.join("\n") + "\n";
}

/** `.env.example` content with descriptions and safe defaults. */
export function toEnvExample(schema) {
  const lines = ["# Generated by EnvSafe. Copy to .env and fill in the values.", ""];
  for (const [key, rule] of Object.entries(schema)) {
    const tags = [rule.type || "string"];
    if (rule.required) tags.push("required");
    if (rule.secret) tags.push("secret");
    if (rule.description) lines.push(`# ${rule.description}`);
    lines.push(`# ${tags.join(", ")}`);
    if (rule.type === "enum") lines.push(`# allowed: ${(rule.values || []).join(", ")}`);
    const placeholder = rule.secret ? "" : rule.default !== undefined ? String(rule.default) : "";
    lines.push(`${key}=${placeholder}`, "");
  }
  return lines.join("\n").trimEnd() + "\n";
}
